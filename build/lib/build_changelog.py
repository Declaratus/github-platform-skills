#!/usr/bin/env python3
"""Write each docs plugin's changelog.md from the GitHub Changelog REST API.

The changelog has no git source, so nothing is pinned. Each run lists entries
for the plugin's labels from (docs snapshot date - lookback_days) to now, where
the snapshot date is upstream_committed_at in the plugin's references/SOURCE.json.
Docs lag the changelog, so the lookback keeps recent entries the snapshot may
not cover yet. Config lives in build/changelog.json. Stdlib only.
"""
import argparse
import html
import json
import re
import sys
import urllib.parse
import urllib.request
from datetime import datetime, timedelta, timezone
from pathlib import Path

USER_AGENT = 'github-platform-skills-build'
TYPES = {'new-releases': 'New', 'improvements': 'Improvement', 'deprecations': 'Deprecation'}


def get(url):
    request = urllib.request.Request(url, headers={'User-Agent': USER_AGENT, 'Accept': 'application/json'})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response), int(response.headers.get('X-WP-TotalPages', '1'))


def term_ids(api, taxonomy, slugs):
    query = urllib.parse.urlencode({'slug': ','.join(slugs), 'per_page': 100, '_fields': 'id,slug'})
    terms, _ = get(f'{api}/{taxonomy}?{query}')
    found = {t['slug']: t['id'] for t in terms}
    missing = sorted(set(slugs) - set(found))
    if missing:
        raise ValueError(f'Unknown changelog {taxonomy} slug(s): {", ".join(missing)}')
    return found


def entries(api, label_ids, after):
    params = {'label': ','.join(map(str, label_ids)), 'after': after, 'per_page': 100,
              'orderby': 'date', 'order': 'desc', '_fields': 'date_gmt,link,title,type,excerpt'}
    page, pages, result = 1, 1, []
    while page <= pages:
        batch, pages = get(f'{api}/changelogs?{urllib.parse.urlencode({**params, "page": page})}')
        result.extend(batch)
        page += 1
    return result


def text(rendered):
    return html.unescape(re.sub(r'<[^>]+>', '', rendered)).strip()


def render(title, labels, window_start, generated_at, rows):
    feeds = '\n'.join(f'- https://github.blog/changelog/label/{slug}/feed/' for slug in labels)
    table = '\n'.join(f'| {r["date"]} | {r["type"]} | [{r["title"].replace("|", "/")}]({r["link"]}) |' for r in rows)
    return f"""<!-- Generated by build/lib/build_changelog.py from build/changelog.json. Do not edit. -->
# {title} changes newer than the docs snapshot

github/docs does not carry the GitHub Changelog. The bundled `references/` tree is a snapshot (see `upstream_committed_at` in `references/SOURCE.json`), and features often ship, change status or get renamed before the docs catch up.

This list covers {window_start} to {generated_at}. Where an entry and the docs disagree, the newer dated source wins; say which one you used and read the linked entry for scope and limits before relying on it. For anything after {generated_at}, check the label feeds:

{feeds}

Older entries are on `?paged=2`, `?paged=3` and so on.

| Date | Type | Entry |
|---|---|---|
{table}
"""


def build(root, config, name, now):
    plugin = config['plugins'][name]
    skill = root / 'plugins' / name / 'skills' / name
    source = skill / 'references' / 'SOURCE.json'
    if not source.is_file():
        print(f'{name}: skipped, no {source.relative_to(root).as_posix()}')
        return
    snapshot = datetime.fromisoformat(json.loads(source.read_text(encoding='utf-8'))['upstream_committed_at'])
    start = (snapshot - timedelta(days=plugin.get('lookback_days', config['lookback_days']))).date()
    api = config['api']
    labels = term_ids(api, 'label', plugin['labels'])
    types = {v: k for k, v in term_ids(api, 'type', list(TYPES)).items()}
    match = re.compile(plugin['match'], re.I) if plugin.get('match') else None
    rows = []
    for e in entries(api, labels.values(), f'{start}T00:00:00'):
        title = text(e['title']['rendered'])
        if match and not match.search(title + ' ' + text(e['excerpt']['rendered'])):
            continue
        kind = ', '.join(TYPES[types[t]] for t in e['type'] if t in types) or '-'
        rows.append({'date': e['date_gmt'][:10], 'type': kind, 'title': title, 'link': e['link']})
    if not rows:
        raise ValueError(f'{name}: no changelog entries since {start}, refusing to write an empty list')
    out = skill / 'changelog.md'
    out.write_text(render(plugin['title'], plugin['labels'], start, now.date(), rows),
                   encoding='utf-8', newline='\n')
    print(f'{name}: {len(rows)} entries since {start}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo-root', type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument('--config', default='build/changelog.json')
    parser.add_argument('plugins', nargs='*', help='Plugin names; default is every plugin in the config')
    args = parser.parse_args()
    config = json.loads((args.repo_root / args.config).read_text(encoding='utf-8'))
    now = datetime.now(timezone.utc)
    for name in args.plugins or sorted(config['plugins']):
        build(args.repo_root, config, name, now)


if __name__ == '__main__':
    sys.exit(main())
